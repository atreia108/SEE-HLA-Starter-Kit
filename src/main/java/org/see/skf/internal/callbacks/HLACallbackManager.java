    // N.B. This method is purely for the case when an object instance is discovered, and we have no starting values to provide its
    // local representation in the federate. The actual update is done through the reflectAttributeValues callback in SKFederateAmbassador
    // but the Future returned here can at least block the thread until the initial values are received and we're ready to send out the
    // event generated by ObjectInstanceListener::created().
    public Future<Void> invokeInstanceDiscoveryValueAcquisitionCallback(String instanceName, ObjectInstanceHandle instanceHandle, AttributeHandleSet subscribedAttributes) {
        IAbstractBiCallback<ObjectInstanceHandle, Void> callback = new IAbstractBiCallbackImpl<>(instanceHandle,1);
        this.instanceDiscoveryValueAcquisitionCallbacks2.add(callback);

        FutureTask<Void> task = callback.getTask();
        this.executor.submit(task);

        try {
            rtiAmbassador.requestAttributeValueUpdate(instanceHandle, subscribedAttributes, null);
        } catch (AttributeNotDefined | ObjectInstanceNotKnown | SaveInProgress | RestoreInProgress |
                 FederateNotExecutionMember | NotConnected | RTIinternalError e) {
            throw new RuntimeException("Failed to dispatch attribute value update request for the discovered object instance <" + instanceName + ">.", e);
        }

        return task;

        /*
        InstanceDiscoveryValueAcquisitionCallback callback = new InstanceDiscoveryValueAcquisitionCallback(instanceHandle, null);
        this.instanceDiscoveryValueAcquisitionCallbacks.add(callback);
        FutureTask<Void> task = callback.getTask();
        this.executor.submit(task);

        try {
            rtiAmbassador.requestAttributeValueUpdate(instanceHandle, subscribedAttributes, null);
        } catch (AttributeNotDefined | ObjectInstanceNotKnown | SaveInProgress | RestoreInProgress |
                 FederateNotExecutionMember | NotConnected | RTIinternalError e) {
            throw new RuntimeException("Failed to dispatch attribute value update request for the discovered object instance <" + instanceName + ">.", e);
        }

        return callback.getTask();
         */
    }

